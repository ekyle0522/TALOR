        if (a < 0) a += 2 * Math.PI;
        const i = Math.round((a / (2 * Math.PI)) * this.n) % this.n;
        svg.classList.add("is-hover");
        this.hoverSpoke.setAttribute("x2", this.cx + this.R * Math.cos(this.angle(i)));
        this.hoverSpoke.setAttribute("y2", this.cy + this.R * Math.sin(this.angle(i)));
        this.labels.forEach((l, k) => l.classList.toggle("is-hover", k === i));
        const c = SUITE[this.suite].corruptions[i];
        const rows = RADAR_SERIES.map((sr) =>
          `<div class="tt-row"><span><i class="tt-sw" style="background:${sr.color}"></i>${sr.label}</span><span>${U.fmt(this.values[sr.key][i])}</span></div>`).join("");
