  class HeroSpectrum {
    constructor(fig) {
      this.fig = fig;
      this.stage = fig.querySelector(".spectrum-svg");
      this.build();
      U.watchWidth(this.stage, () => this.build());
    }

    build() {
      const W = Math.max(280, this.stage.clientWidth);
      const H = Math.max(100, this.stage.clientHeight);
      const sig = D.spectrum.sigma;
      const n = sig.length;
      const k = D.spectrum.k;
      const top = 6;
      const base = H - 24;
      const step = W / n;
      const xOf = (i) => (i + 0.5) * step;
      const svg = newSvg(this.stage, W, H, "spectrum");
      const bar = (from, to) => {
        let d = "";
        for (let i = from; i < to; i++) {
          d += `M${xOf(i).toFixed(2)} ${base}V${(base - (base - top) * (sig[i] / sig[0])).toFixed(2)}`;
        }
        return d;
      };
      const sw = Math.max(0.6, step * 0.62).toFixed(2);
      const gp = U.svg("g", { class: "bars bars-principal" }, svg);
      U.svg("path", { d: bar(0, k), "stroke-width": sw }, gp);
      const gt = U.svg("g", { class: "bars bars-tail" }, svg);
      U.svg("path", { d: bar(k, n), "stroke-width": sw }, gt);
      const xc = k * step;
      U.svg("line", { class: "cut-line", x1: xc, x2: xc, y1: 0, y2: base + 2 }, svg);
      U.svg("text", { class: "bar-label principal", x: xOf(k / 2), y: H - 4, "text-anchor": "middle", text: `${k} principal directions` }, gp);
      U.svg("text", { class: "bar-label tail", x: xOf((k + n) / 2), y: H - 4, "text-anchor": "middle", text: `${n - k} tail directions` }, gt);
      this.fig.style.setProperty("--cut-x", `${((xc / W) * 100).toFixed(2)}%`);
    }
  }

