  class SplitChart {
    constructor(el, outEl) {
      this.el = el;
      this.outEl = outEl;
      const sigma = D.spectrum.sigma;
      const total = sigma.reduce((a, s) => a + s * s, 0);
      let acc = 0;
      this.energy = sigma.map((s) => (acc += s * s) / total);
      this.tau = 0.8;
      this.build();
      U.watchWidth(el, () => this.build());
    }

    kFor(tau) {
      const s = D.spectrum.sigma.length;
      let k0 = s;
      for (let j = 0; j < s; j++) {
        if (this.energy[j] >= tau - 1e-12) { k0 = j + 1; break; }
      }
      return Math.min(k0, s - 1);
    }

    build() {
      const W = Math.max(300, this.el.clientWidth);
      const small = W < 560;
      const H = small ? 230 : 270;
      const m = { l: 44, r: small ? 40 : 52, t: 28, b: 36 };
      const n = D.spectrum.sigma.length;
      this.x = U.linear(0, n, m.l, W - m.r);
      this.y = U.linear(0, 2.15, H - m.b, m.t);
      this.y2 = U.linear(0, 1, H - m.b, m.t);
      Object.assign(this, { W, H, m, n, small });
      const svg = newSvg(this.el, W, H, "split");
      this.svg = svg;
      const axis = U.svg("g", { class: "axis" }, svg);
      [0, 0.5, 1, 1.5, 2].forEach((v) => {
        U.svg("line", { class: "gridline", x1: m.l, x2: W - m.r, y1: this.y(v), y2: this.y(v) }, axis);
        U.svg("text", { class: "tick", x: m.l - 8, y: this.y(v) + 4, "text-anchor": "end", text: v }, axis);
      });
      [0, 0.5, 1].forEach((v) => U.svg("text", { class: "tick", x: W - m.r + 8, y: this.y2(v) + 4, text: `${v * 100}%` }, axis));
      [1, 200, 400, 600, n].forEach((v) => U.svg("text", { class: "tick", x: this.x(v - 0.5), y: H - m.b + 18, "text-anchor": "middle", text: v }, axis));
      U.svg("text", { class: "axis-title", x: (m.l + W - m.r) / 2, y: H - 3, "text-anchor": "middle", text: "singular direction j of the head (sorted)" }, svg);
      U.svg("text", { class: "axis-title", x: m.l, y: m.t - 12, "text-anchor": "start", text: "singular value σ" }, svg);
      U.svg("text", { class: "axis-title", x: W - m.r + 6, y: m.t - 12, "text-anchor": "end", text: "cumulative energy" }, svg);
      this.areaP = U.svg("path", { class: "area-principal" }, svg);
      this.areaT = U.svg("path", { class: "area-tail" }, svg);
      const pts = this.energy.map((e, j) => `${this.x(j + 1).toFixed(1)} ${this.y2(e).toFixed(1)}`);
      U.svg("path", { class: "energy", d: `M${this.x(0).toFixed(1)} ${this.y2(0).toFixed(1)}L` + pts.join("L") }, svg);
      this.tauLine = U.svg("line", { class: "tau-line" }, svg);
      this.kLine = U.svg("line", { class: "k-line" }, svg);
      this.kDot = U.svg("circle", { class: "k-dot", r: 5 }, svg);
      this.labP = U.svg("text", { class: "lab principal", "text-anchor": "middle" }, svg);
      this.labT = U.svg("text", { class: "lab tail", "text-anchor": "middle" }, svg);
      this.labTau = U.svg("text", { class: "lab energy-lab", "text-anchor": "end" }, svg);
      this.setTau(this.tau);
    }

    area(from, to) {
      const sig = D.spectrum.sigma;
      const base = this.y(0).toFixed(1);
      let d = `M${this.x(from).toFixed(1)} ${base}`;
      for (let j = from; j < to; j++) {
        const yy = this.y(sig[j]).toFixed(1);
        d += `L${this.x(j).toFixed(1)} ${yy}L${this.x(j + 1).toFixed(1)} ${yy}`;
      }
      return d + `L${this.x(to).toFixed(1)} ${base}Z`;
    }

    setTau(tau) {
      this.tau = tau;
      const k = this.kFor(tau);
      const n = this.n;
      this.areaP.setAttribute("d", this.area(0, k));
      this.areaT.setAttribute("d", this.area(k, n));
      const xk = this.x(k);
      const ek = this.energy[k - 1];
      this.tauLine.setAttribute("x1", this.m.l);
      this.tauLine.setAttribute("x2", xk);
      this.tauLine.setAttribute("y1", this.y2(tau));
      this.tauLine.setAttribute("y2", this.y2(tau));
      this.kLine.setAttribute("x1", xk);
      this.kLine.setAttribute("x2", xk);
      this.kLine.setAttribute("y1", this.y2(ek));
      this.kLine.setAttribute("y2", this.y(0));
      this.kDot.setAttribute("cx", xk);
      this.kDot.setAttribute("cy", this.y2(ek));
      const midP = this.x(k / 2);
      const midT = this.x((k + n) / 2);
      this.labP.setAttribute("x", U.clamp(midP, this.m.l + 50, xk - 50));
      this.labP.setAttribute("y", this.y(0) - 10);
      this.labP.textContent = `principal · ${k}`;
      this.labT.setAttribute("x", U.clamp(midT, xk + 40, this.W - this.m.r - 30));
      this.labT.setAttribute("y", this.y(0) - 10);
      this.labT.textContent = `tail · ${n - k}`;
      // white inside the area when it is tall enough, otherwise coloured text above it
      const sig = D.spectrum.sigma;
      const fit = (label, mid, color) => {
        const j = U.clamp(Math.round(this.x.invert(mid)), 0, n - 1);
        const room = this.y(0) - this.y(sig[j]);
        label.setAttribute("fill", room >= 24 ? "#fff" : color);
        label.setAttribute("y", room >= 24 ? this.y(0) - 9 : this.y(sig[j]) - 8);
      };
      fit(this.labP, Number(this.labP.getAttribute("x")), COL.principal);
      fit(this.labT, Number(this.labT.getAttribute("x")), COL.tail);
      this.labTau.setAttribute("x", xk - 10);
      this.labTau.setAttribute("y", this.y2(tau) - 8);
      this.labTau.textContent = `τ = ${tau.toFixed(2)}`;
      if (this.outEl) {
        this.outEl.innerHTML = `τ = ${tau.toFixed(2)} → <b>${k}</b> principal · <b>${n - k}</b> tail` +
          (Math.abs(tau - 0.8) < 1e-9 ? " <span class=\"tt-default\">(TALOR's setting)</span>" : "");
      }
    }
  }

